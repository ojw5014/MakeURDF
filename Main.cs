        /// <summary>3D에서 피킹된 오브젝트의 DH 라인 인덱스를 찾음</summary>
        private int FindDhLineFromPickGroups(int nGroupA, int nGroupB)
        {
            if (m_C3d == null) return -1;
            int cnt = m_C3d.User_GetCnt();
            if (cnt <= 0) return -1;

            for (int i = 0; i < cnt; i++)
            {
                try
                {
                    var disp = m_C3d.User_Get(i);
                    if (disp == null) continue;
                    if (disp.nPickGroup_A == nGroupA && disp.nPickGroup_B == nGroupB && nGroupA > 0)
                        return disp.GetDhLine();
                }
                catch { break; }
            }
            return -1;
        }

