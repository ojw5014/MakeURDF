        private void UpdateWristMotorCombo(string dhString)
        {
            List<int> ids = ExtractMotorIds(dhString);
            int prevSelected = GetSelectedWristMotorId();

            cmbWristMotor.Items.Clear();
            cmbWristMotor.Items.Add("없음 (전체 팔)");
            foreach (int id in ids)
                cmbWristMotor.Items.Add(string.Format("M{0} 뒤부터", id));

            // 이전 선택 복원
            if (prevSelected >= 0)
            {
                for (int i = 1; i < cmbWristMotor.Items.Count; i++)
                {
                    if (ids[i - 1] == prevSelected)
                    {
                        cmbWristMotor.SelectedIndex = i;
                        return;
                    }
                }
            }
            cmbWristMotor.SelectedIndex = 0;
        }

