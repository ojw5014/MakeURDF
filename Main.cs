        /// <summary>수식 콤보 갱신 (MakeAll 완료 후 호출)</summary>
        private void UpdateFormulaCombo()
        {
            if (cmbFuncNum == null || m_C3d == null) return;

            int prevFunc = GetSelectedFuncNum();
            cmbFuncNum.Items.Clear();

            if (m_lstFormulaGroups == null || m_lstFormulaGroups.Count <= 1)
            {
                // 단일 체인: "0: 전체"
                cmbFuncNum.Items.Add("0: \uc804\uccb4");
            }
            else
            {
                // 멀티 체인: 각 체인 + 전체
                for (int i = 0; i < m_lstFormulaGroups.Count; i++)
                {
                    // 이 체인의 모터 목록 수집
                    string motorStr = "";
                    try
                    {
                        int[] mids = m_C3d.CalcInv_MotorIDs(i);
                        if (mids != null && mids.Length > 0)
                        {
                            List<string> ms = new List<string>();
                            for (int j = 0; j < mids.Length; j++) ms.Add("M" + mids[j]);
                            motorStr = string.Join(",", ms.ToArray());
                        }
                    }
                    catch { }
                    string name = (motorStr.Length > 0)
                        ? string.Format("{0}: {1}({2})", i, m_lstFormulaGroups[i].Name, motorStr)
                        : string.Format("{0}: {1}", i, m_lstFormulaGroups[i].Name);
                    cmbFuncNum.Items.Add(name);
                }
                // 전체 수식
                cmbFuncNum.Items.Add(m_lstFormulaGroups.Count + ": \uc804\uccb4");
            }

            // 기본값: "전체" = 마지막 항목
            cmbFuncNum.SelectedIndex = cmbFuncNum.Items.Count - 1;
        }

