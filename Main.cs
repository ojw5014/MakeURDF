        // ========================================
        // 렌더 루프 (Kinematics:539 패턴)
        // ========================================
        private void tmrDisp_Tick(object sender, EventArgs e)
        {
            if (m_C3d == null) return;
            m_C3d.OjwDraw();

            // 피킹 이벤트 체크: 3D 클릭 → 해당 히스토리 항목 선택 + DH 텍스트 줄 선택
            // STL 면 선택은 OnC3dMouseUp → TrySelectStlFace에서 레이캐스트로 처리
            if (m_C3d.GetEvent_Pick())
            {
                int nGroup, nMotor, nServeGroup, nKinematicsNum;
                m_C3d.GetEvent_Pick_Data(out nGroup, out nMotor, out nServeGroup, out nKinematicsNum);

                // 끝점 좌표축 표시볼 클릭 처리 (MakeDhSkeleton_Direction: nGroup=255, nPickGroup_C=253/254/255 → 7비트로 125/126/127)
                // nPickGroup_C는 7비트만 저장 (& 0x7f): 253→125, 254→126, 255→127
                if (m_eMode == InteractionMode.Mouse && nGroup == 255 && nServeGroup >= 125 && nServeGroup <= 127)
                {
                    OnAxisHandlePicked(nServeGroup == 125 ? PICK_AXIS_X :
                                       nServeGroup == 126 ? PICK_AXIS_Y : PICK_AXIS_Z);
                    return;
                }

                m_bSyncingSelection = true;
                try
                {
                    SelectHistoryByPickGroup(nMotor);

                    // 3D 피킹 → DH 텍스트 줄 역방향 선택
                    int dhLine = FindDhLineFromPickGroups(nGroup, nMotor);
                    if (dhLine >= 0)
                        SelectDhTextLineByDhIndex(dhLine);
                    else
                        ClearDhEditSelection();
                }
                finally { m_bSyncingSelection = false; }
            }
        }

        // ========================================
        // MakeAll - DH 문자열로 3D 갱신 (Kinematics:666 패턴)
        // ========================================
        private void MakeAll(string dhString)
        {
            if (m_C3d == null) return;
            if (string.IsNullOrEmpty(dhString) || dhString.Trim().Length == 0)
                dhString = " ";

            // ── 체인 분할 & 수식 슬롯 할당 ──
            List<DhGroup> groups = SplitDhByInit(dhString);
            m_lstFormulaGroups = groups;
            m_nFormulaCount = groups.Count;

            // 기존 수식 슬롯 클리어
            for (int i = 0; i <= groups.Count && i < 512; i++)
                m_C3d.m_CHeader.pstrKinematics[i] = null;

            // 각 체인을 별도 수식 슬롯에 저장
            for (int i = 0; i < groups.Count; i++)
            {
                string chainDh = StripInitFlag(groups[i].DhText);
                m_C3d.m_CHeader.pstrKinematics[i] = chainDh;
            }

            m_C3d.CheckForward();

            // 전체 수식: 개별 체인 컴파일 결과를 합쳐서 pDhParamAll[N]에 직접 할당
            if (groups.Count > 1)
            {
                CDhParamAll merged = new CDhParamAll();
                for (int i = 0; i < groups.Count; i++)
                {
                    CDhParamAll src = m_C3d.m_CHeader.pDhParamAll[i];
                    if (src == null) continue;
                    int cnt = src.GetCount();
                    for (int j = 0; j < cnt; j++)
                    {
                        CDhParam dp = src.GetData(j);
                        if (dp != null) merged.AddData(dp);
                    }
                }
                m_C3d.m_CHeader.pDhParamAll[groups.Count] = merged;
            }

            // 3D 렌더링용 DH 텍스트 (Type=2,Num 매핑 적용)
            string mappedDh = BuildFormulaMappedDh(dhString, groups);

            String strUrdfCommand = "";
            String strUrdfXml = "";

            // 뷰 모드에 따라 스켈레톤/STL 가시성 결정
            bool bShowSkeleton = true, bShowMesh = true;
            GetViewModeFlags(out bShowSkeleton, out bShowMesh);

            float fSkeletonSize = Ojw.CConvert.StrToFloat(txtSkeletonSize.Text);
            if (fSkeletonSize <= 0) fSkeletonSize = 10.0f;
            float fAxisSize = Ojw.CConvert.StrToFloat(txtAxisSize.Text);
            if (fAxisSize <= 0) fAxisSize = 20.0f;

            m_C3d.m_CHeader.strDrawModel = m_C3d.MakeDHSkeleton_Urdf(
                true,              // bDrawing
                true,              // bInit
                bShowSkeleton,     // bVisibleSkeleton
                bShowMesh,         // bVisibleMesh
                fSkeletonSize,     // fSize (바 크기)
                fAxisSize,         // fAxisSize (축 크기)
                Color.Violet,      // cColor
                mappedDh,          // strString (수식번호 매핑 적용)
                0,                 // nStartGroupNumber
                0, 0, 0,           // offset X, Y, Z
                0, 0, 0,           // offset Pan, Tilt, Swing
                ref txtMessage,
                ref strUrdfCommand,
                ref strUrdfXml);

            m_C3d.CompileDesign();

            // 면 축 정렬 모드: 스켈레톤 반투명 처리
            if (m_bMergeMode)
                m_C3d.ApplySkeletonAlpha(0.15f);

            // 수식 콤보 갱신
            UpdateFormulaCombo();

            // 손목 경계 콤보 갱신
            UpdateWristMotorCombo(dhString);

            // 그리퍼 모터 콤보 갱신
            UpdateGripperMotorCombo(dhString);
        }

