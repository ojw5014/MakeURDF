        /// <summary>Go (IK): 좌표 → 각도 계산 (선택된 알고리즘 사용)</summary>
        private void btnGoIk_Click(object sender, EventArgs e)
        {
            if (m_C3d == null) return;

            int funcNum = GetSelectedFuncNum();
            float fX = Ojw.CConvert.StrToFloat(txtIkX.Text);
            float fY = Ojw.CConvert.StrToFloat(txtIkY.Text);
            float fZ = Ojw.CConvert.StrToFloat(txtIkZ.Text);

            int ikType = cmbCalcInvMode.SelectedIndex;
            // 0: CCDIK, 1: FABRIK, 2: Jacobian, 3: Jacob+손목, 4: 수식편집기

            try
            {
                int[] motorIds = m_C3d.CalcInv_MotorIDs(funcNum);
                bool bSuccess = false;
                float[] angles = null;
                string algName = cmbCalcInvMode.SelectedItem.ToString();

                switch (ikType)
                {
                    case 0: // CCDIK
                        m_C3d.CalcInv_SetIKAlgorithm(0);
                        angles = m_C3d.CalcInv(funcNum, fX, fY, fZ);
                        bSuccess = (angles != null);
                        break;

                    case 1: // FABRIK
                        m_C3d.CalcInv_SetIKAlgorithm(1);
                        angles = m_C3d.CalcInv(funcNum, fX, fY, fZ);
                        bSuccess = (angles != null);
                        break;

                    case 2: // Jacobian (위치만)
                        bSuccess = Ojw.CKinematics.CInverse.SolveIK_JacobianDLS_PosOnly(
                            ref m_C3d, funcNum, fX, fY, fZ,
                            100, 0.1f, 0.01f, 0.5f, 1.0f, 5.0f);
                        if (bSuccess && motorIds != null)
                        {
                            angles = new float[motorIds.Length];
                            for (int i = 0; i < motorIds.Length; i++)
                                angles[i] = m_C3d.GetData(motorIds[i]);
                        }
                        break;

                    case 3: // Jacobian + 손목
                        bSuccess = Ojw.CKinematics.CInverse.SolveIK_JacobianDLS_PosWithTool(
                            ref m_C3d, funcNum, fX, fY, fZ,
                            0, 0, 0, 0,   // rx, ry, rz, toolLength (기본값)
                            100, 0.1f, 0.01f, 0.5f, 1.0f, 5.0f);
                        if (bSuccess && motorIds != null)
                        {
                            angles = new float[motorIds.Length];
                            for (int i = 0; i < motorIds.Length; i++)
                                angles[i] = m_C3d.GetData(motorIds[i]);
                        }
                        break;

                    case 4: // 수식편집기 (CallInverse nType=0)
                        angles = m_C3d.CalcInv(funcNum, fX, fY, fZ);
                        bSuccess = (angles != null);
                        break;
                }

                if (bSuccess && angles != null && motorIds != null)
                {
                    string result = "";
                    for (int i = 0; i < motorIds.Length && i < angles.Length; i++)
                        result += String.Format("[M{0}]={1:F1}\u00b0 ", motorIds[i], angles[i]);
                    lblStatus.Text = algName + " \uacb0\uacfc: " + result;
                    lblCurrentValue.Text = String.Format("({0}, {1}, {2})", fX, fY, fZ);
                }
                else
                {
                    lblStatus.Text = algName + " \uacc4\uc0b0 \uc2e4\ud328 (\uc218\uc2dd\ubc88\ud638 \ud655\uc778)";
                }
            }
            catch (Exception ex)
            {
                lblStatus.Text = "IK \uc624\ub958: " + ex.Message;
            }

            RefreshMotorAngle();
        }

