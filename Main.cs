        /// <summary>DH 라인의 Init 필드(인덱스 6)를 newInit으로 교체</summary>
        /// <remarks>
        /// 괄호 형식 [A,D,Theta,Alpha],[Axis,Dir,Init,Type,Num] 에서 7번째 필드 수정.
        /// Type,Num 필드가 있으면 보존.
        /// </remarks>
        private string ReplaceInitField(string line, int newInit)
        {
            // 주석 분리
            string data = line;
            string comment = "";
            int cp = line.IndexOf("//");
            if (cp >= 0) { data = line.Substring(0, cp); comment = line.Substring(cp); }

            // 괄호 제거 후 파싱
            string cleaned = data.Replace("[", "").Replace("]", "");
            string[] parts = cleaned.Split(',');
            if (parts.Length < 7) return line; // Init 필드 없음

            // Init 필드(인덱스 6) 교체
            parts[6] = newInit.ToString();

            // 원래 괄호 형식으로 재조립
            // [A,D,Theta,Alpha],[Axis,Dir,Init] 또는 [A,D,Theta,Alpha],[Axis,Dir,Init,Type,Num]
            string result;
            if (parts.Length <= 7)
                result = string.Format("[{0},{1},{2},{3}],[{4},{5},{6}]",
                    parts[0].Trim(), parts[1].Trim(), parts[2].Trim(), parts[3].Trim(),
                    parts[4].Trim(), parts[5].Trim(), parts[6].Trim());
            else if (parts.Length == 9)
                result = string.Format("[{0},{1},{2},{3}],[{4},{5},{6},{7},{8}]",
                    parts[0].Trim(), parts[1].Trim(), parts[2].Trim(), parts[3].Trim(),
                    parts[4].Trim(), parts[5].Trim(), parts[6].Trim(),
                    parts[7].Trim(), parts[8].Trim());
            else
            {
                // 기타 길이: 괄호 없이 콤마 재조립
                List<string> trimmed = new List<string>();
                for (int k = 0; k < parts.Length; k++) trimmed.Add(parts[k].Trim());
                result = string.Join(",", trimmed.ToArray());
            }

            if (comment.Length > 0) result += " " + comment;
            return result;
        }

        /// <summary>DH 라인의 Type,Num 필드를 설정/갱신 (인덱스 7,8)</summary>
        private string SetTypeNumField(string line, int type, int num)
        {
            // 주석 분리
            string data = line;
            string comment = "";
            int cp = line.IndexOf("//");
            if (cp >= 0) { data = line.Substring(0, cp); comment = line.Substring(cp); }

            string cleaned = data.Replace("[", "").Replace("]", "");
            string[] parts = cleaned.Split(',');
            if (parts.Length < 7) return line; // 기본 DH 필드 부족

            // parts를 최소 9개로 확장
            string[] newParts = new string[9];
            for (int k = 0; k < 9; k++)
                newParts[k] = (k < parts.Length) ? parts[k].Trim() : "0";
            newParts[7] = type.ToString();
            newParts[8] = num.ToString();

            string result = string.Format("[{0},{1},{2},{3}],[{4},{5},{6},{7},{8}]",
                newParts[0], newParts[1], newParts[2], newParts[3],
                newParts[4], newParts[5], newParts[6], newParts[7], newParts[8]);

            if (comment.Length > 0) result += " " + comment;
            return result;
        }

        /// <summary>개별 체인 DH에서 첫 번째 Init=1을 Init=0으로 변경</summary>
        private string StripInitFlag(string chainDhText)
        {
            string[] lines = chainDhText.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            for (int i = 0; i < lines.Length; i++)
            {
                string trimmed = lines[i].Trim();
                if (trimmed.Length == 0 || trimmed.StartsWith("//") || trimmed.StartsWith("@") || trimmed.StartsWith("#"))
                    continue;
                // 첫 유효 DH 라인 → Init 필드를 0으로
                lines[i] = ReplaceInitField(lines[i], 0);
                break;
            }
            return string.Join("\r\n", lines);
        }

        /// <summary>전체 DH 텍스트에서 모든 Init=1을 Init=0으로 변경</summary>
        /// <remarks>
        /// 전체 수식 슬롯에 저장할 때 사용.
        /// MakeDhParam에서 DeleteAll()이 호출되지 않아 모든 모터가 누적됨.
        /// </remarks>
        private string StripAllInitFlags(string fullDhText)
        {
            string[] lines = fullDhText.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            for (int i = 0; i < lines.Length; i++)
            {
                string trimmed = lines[i].Trim();
                if (trimmed.Length == 0 || trimmed.StartsWith("//") || trimmed.StartsWith("@") || trimmed.StartsWith("#"))
                    continue;

                // Init 필드 확인
                string s = trimmed;
                int cpos = s.IndexOf("//");
                if (cpos >= 0) s = s.Substring(0, cpos);
                s = s.Replace("[", "").Replace("]", "").Trim();
                string[] parts = s.Split(',');
                if (parts.Length >= 7)
                {
                    int nInit = 0;
                    int.TryParse(parts[6].Trim(), out nInit);
                    if (nInit == 1)
                        lines[i] = ReplaceInitField(lines[i], 0);
                }
            }
            return string.Join("\r\n", lines);
        }

        /// <summary>3D 렌더링용 DH 텍스트 생성 (Type=2,Num=chainIndex 매핑)</summary>
        /// <remarks>
        /// 각 체인의 마지막 DH 라인에 Type=2,Num=chainIndex를 설정하여
        /// 3D에서 클릭 시 올바른 수식번호로 IK가 연동되도록 한다.
        /// 기존 Type=2 라인은 Num을 갱신하고, Type=1 등 다른 타입은 유지한다.
        /// </remarks>
        private string BuildFormulaMappedDh(string fullDhText, List<DhGroup> groups)
        {
            if (groups.Count <= 1) return fullDhText; // 단일 체인이면 매핑 불필요

            string[] allLines = fullDhText.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);

            // 1단계: 각 텍스트 줄이 어느 체인에 속하는지 매핑
            int[] lineChainMap = new int[allLines.Length]; // -1 = 매핑 없음 (주석/빈줄)
            for (int i = 0; i < allLines.Length; i++) lineChainMap[i] = -1;

            int currentChain = 0;
            int dhLineCount = 0;
            for (int i = 0; i < allLines.Length; i++)
            {
                string trimmed = allLines[i].Trim();
                if (trimmed.Length == 0 || trimmed.StartsWith("//"))
                    continue;

                // Init=1 체크 (DH 라인만, @/#은 현재 체인 소속)
                if (!trimmed.StartsWith("@") && !trimmed.StartsWith("#"))
                {
                    string s = trimmed;
                    int cpos = s.IndexOf("//");
                    if (cpos >= 0) s = s.Substring(0, cpos);
                    s = s.Replace("[", "").Replace("]", "").Trim();
                    string[] parts = s.Split(',');
                    if (parts.Length >= 7)
                    {
                        int nInit = 0;
                        int.TryParse(parts[6].Trim(), out nInit);
                        if (nInit == 1 && dhLineCount > 0)
                        {
                            currentChain++;
                            if (currentChain >= groups.Count) currentChain = groups.Count - 1;
                        }
                    }
                    dhLineCount++;
                }

                lineChainMap[i] = currentChain;
            }

            // 2단계: 각 체인의 마지막 DH 라인 인덱스 찾기 & 기존 Type=2 라인 확인
            int[] lastDhLine = new int[groups.Count];
            bool[] hasType2 = new bool[groups.Count];
            for (int c = 0; c < groups.Count; c++) { lastDhLine[c] = -1; hasType2[c] = false; }

            for (int i = 0; i < allLines.Length; i++)
            {
                if (lineChainMap[i] < 0) continue;
                int chain = lineChainMap[i];

                string trimmed = allLines[i].Trim();
                if (trimmed.StartsWith("@") || trimmed.StartsWith("#")) continue; // STL/함수는 스킵

                lastDhLine[chain] = i;

                // 기존 Type 필드 확인
                string s = trimmed;
                int cpos = s.IndexOf("//");
                if (cpos >= 0) s = s.Substring(0, cpos);
                s = s.Replace("[", "").Replace("]", "").Trim();
                string[] parts = s.Split(',');
                if (parts.Length >= 8)
                {
                    int nType = 0;
                    int.TryParse(parts[7].Trim(), out nType);
                    if (nType == 2)
                    {
                        hasType2[chain] = true;
                        // 기존 Type=2 라인의 Num을 chainIndex로 갱신
                        allLines[i] = SetTypeNumField(allLines[i], 2, chain);
                    }
                }
            }

            // 3단계: Type=2가 없는 체인은 마지막 DH 라인에 추가
            for (int c = 0; c < groups.Count; c++)
            {
                if (!hasType2[c] && lastDhLine[c] >= 0)
                {
                    allLines[lastDhLine[c]] = SetTypeNumField(allLines[lastDhLine[c]], 2, c);
                }
            }

            return string.Join("\r\n", allLines);
        }

        /// <summary>그룹 이름 자동 감지 (주석에서 추출 또는 기본 이름)</summary>
        private string DetectGroupName(List<string> lines, List<string> comments, int groupIdx)
        {
            // 주석에서 Axis 번호 수집
            List<int> axes = new List<int>();
            foreach (string rawLine in lines)
            {
                string ln = rawLine.Trim();
                int cp = ln.IndexOf("//");
                if (cp < 0) continue;
                string cmt = ln.Substring(cp + 2).Trim();
                // "- Axis1", "Axis5" 등에서 번호 추출
                int axIdx = cmt.IndexOf("Axis");
                if (axIdx >= 0)
                {
                    string numStr = "";
                    for (int j = axIdx + 4; j < cmt.Length && (char.IsDigit(cmt[j])); j++)
                        numStr += cmt[j];
                    int axNum;
                    if (int.TryParse(numStr, out axNum) && axNum < 100)
                        axes.Add(axNum);
                }
            }
            if (axes.Count > 0)
            {
                string axisStr = string.Join(",", axes.ConvertAll(a => a.ToString()).ToArray());
                return string.Format("\uadf8\ub8f9 {0} (Axis {1})", groupIdx + 1, axisStr);
            }
            return string.Format("\uadf8\ub8f9 {0}", groupIdx + 1);
        }

