        /// <summary>
        /// STL 드래그 시작: 원본 DhLines를 저장.
        /// </summary>
        private void BeginStlDrag(int stepIdx)
        {
            m_nStlDragStepIdx = stepIdx;
            m_strStlOriginalDhLines = m_Builder.GetStep(stepIdx).DhLines;
        }

        /// <summary>
        /// STL 드래그 중: 원본에 delta를 적용하여 실시간 미리보기.
        /// </summary>
        private void UpdateStlDrag(BuildAction action, float delta)
        {
            if (m_nStlDragStepIdx < 0) return;
            DhStep step = m_Builder.GetStep(m_nStlDragStepIdx);
            step.DhLines = DhBuilder.GetStlPreviewDhLines(m_strStlOriginalDhLines, action, delta);
            UpdatePreview(null);
        }

        /// <summary>
        /// STL 드래그 완료: 최종 delta 적용 확정.
        /// </summary>
        private void EndStlDrag(BuildAction action, float delta)
        {
            if (m_nStlDragStepIdx < 0) return;
            DhStep step = m_Builder.GetStep(m_nStlDragStepIdx);
            if (delta != 0)
                step.DhLines = DhBuilder.GetStlPreviewDhLines(m_strStlOriginalDhLines, action, delta);
            else
                step.DhLines = m_strStlOriginalDhLines; // delta 0이면 원복
            m_nStlDragStepIdx = -1;
            m_strStlOriginalDhLines = "";
        }

        /// <summary>
        /// STL 드래그 취소: 원본 DhLines로 원복.
        /// </summary>
        private void CancelStlDrag()
        {
            if (m_nStlDragStepIdx < 0) return;
            m_Builder.GetStep(m_nStlDragStepIdx).DhLines = m_strStlOriginalDhLines;
            m_nStlDragStepIdx = -1;
            m_strStlOriginalDhLines = "";
            UpdatePreview(null);
        }

