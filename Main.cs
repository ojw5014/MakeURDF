        private void RefreshHistory(int selectIndex = -1)
        {
            m_bSyncingSelection = true;
            lstHistory.Items.Clear();
            for (int i = 0; i < m_Builder.StepCount; i++)
            {
                lstHistory.Items.Add(string.Format("[{0}] {1}",
                    i + 1, m_Builder.GetStep(i).Description));
            }
            if (selectIndex >= 0 && selectIndex < lstHistory.Items.Count)
                lstHistory.SelectedIndex = selectIndex;
            else if (lstHistory.Items.Count > 0)
                lstHistory.SelectedIndex = lstHistory.Items.Count - 1;
            m_bSyncingSelection = false;
        }

