        // 축 버튼 클릭 (모드별 분기)
        // ========================================
        private void HandleAxisButton(BuildAction action, string axisName)
        {
            switch (m_eMode)
            {
                case InteractionMode.Mouse:
                    // 축 선택 → 3D 드래그 대기
                    m_eCurrentAction = action;
                    lblStatus.Text = "3D를 드래그하세요 (" + axisName + ")";
                    lblCurrentValue.Text = "0";
                    break;

                case InteractionMode.Button:
                    // 이동/회전에 따라 다른 입력창에서 값 읽기
                    bool isRotAction = DhBuilder.IsRotation(action);
                    string inputText = isRotAction ? txtRotateValue.Text : txtMoveValue.Text;
                    float value;
                    if (!float.TryParse(inputText, out value))
                    {
                        lblStatus.Text = "숫자를 입력해주세요!";
                        return;
                    }
                    if (value == 0)
                    {
                        lblStatus.Text = "0이 아닌 값을 입력해주세요!";
                        return;
                    }

                    // STL 선택 시: STL 오프셋/회전 직접 수정
                    int stlIdx = GetSelectedStlStepIndex();
                    if (stlIdx >= 0)
                    {
                        DhStep stlStep = m_Builder.GetStep(stlIdx);
                        DhBuilder.ApplyStlDelta(stlStep, action, value);
                        UpdatePreview(null);
                        bool isRotS = DhBuilder.IsRotation(action);
                        string unit = isRotS ? "도" : "mm";
                        lblStatus.Text = string.Format("STL {0} {1:+0;-0}{2}",
                            DhBuilder.GetAxisName(action), value, unit);
                        lblCurrentValue.Text = string.Format("{0}{1}", (int)value, unit);
                        break;
                    }

                    DhStep step = DhBuilder.CreateStep(action, value);
                    m_Builder.AddStep(step);
                    RefreshHistory();
                    UpdatePreview(null);
                    lblStatus.Text = step.Description + " 추가!";
                    bool isRot = DhBuilder.IsRotation(action);
                    lblCurrentValue.Text = string.Format("{0}{1}", (int)value, isRot ? "도" : "mm");
                    break;

                case InteractionMode.Hybrid:
                    // 축 선택 → 드래그 영역 대기
                    m_eCurrentAction = action;
                    lblStatus.Text = "드래그 영역을 드래그하세요 (" + axisName + ")";
                    lblCurrentValue.Text = "0";
                    break;
            }
        }

