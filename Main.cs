        /// <summary>모터 목록 갱신 (선택된 수식번호에 따라)</summary>
        /// <remarks>
        /// 개별 체인 수식: CalcInv_MotorIDs()로 해당 체인의 모터만 표시.
        /// 전체 수식 또는 단일 체인: DH 텍스트를 직접 파싱하여 모든 모터 수집.
        /// </remarks>
        private void UpdateMotorList()
        {
            if (cmbMotorCtrl == null) return;

            cmbMotorCtrl.Items.Clear();
            try
            {
                int funcNum = GetSelectedFuncNum();
                List<int> motorIds = new List<int>();

                // 개별 체인 또는 전체(merge) 수식이면 CalcInv_MotorIDs 사용
                if (m_C3d != null && m_nFormulaCount > 1 && funcNum >= 0 && funcNum <= m_nFormulaCount)
                {
                    int[] mids = m_C3d.CalcInv_MotorIDs(funcNum);
                    if (mids != null)
                    {
                        for (int i = 0; i < mids.Length; i++)
                            if (!motorIds.Contains(mids[i])) motorIds.Add(mids[i]);
                    }
                }
                else
                {
                    // 전체 또는 단일 체인: DH 텍스트 직접 파싱
                    string[] lines = txtDhParams.Lines;
                    for (int i = 0; i < lines.Length; i++)
                    {
                        string line = lines[i].Trim();
                        if (line.Length == 0 || line.StartsWith("//") || line.StartsWith("@") || line.StartsWith("#"))
                            continue;
                        string cleaned = line.Replace("[", "").Replace("]", "");
                        string[] parts = cleaned.Split(',');
                        if (parts.Length > 4)
                        {
                            int nAxis = Ojw.CConvert.StrToInt(parts[4].Trim());
                            if (nAxis >= 0 && !motorIds.Contains(nAxis))
                                motorIds.Add(nAxis);
                        }
                    }
                }

                motorIds.Sort();
                for (int i = 0; i < motorIds.Count; i++)
                    cmbMotorCtrl.Items.Add("M" + motorIds[i].ToString());
            }
            catch { }

            // 모터가 없으면 안내
            if (cmbMotorCtrl.Items.Count == 0)
                cmbMotorCtrl.Items.Add("(\uc5c6\uc74c)");

            cmbMotorCtrl.SelectedIndex = 0;
        }

