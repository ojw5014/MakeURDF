        {
            // XML을 C#에서 직접 구문 하이라이팅하여 HTML 생성
            StringBuilder h = new StringBuilder();
            h.AppendLine("<!DOCTYPE html>");
            h.AppendLine("<html lang=\"ko\"><head><meta charset=\"UTF-8\">");
            h.AppendLine("<title>URDF Viewer</title>");
            h.AppendLine("<style>");
            h.AppendLine("*{margin:0;padding:0;box-sizing:border-box}");
            h.AppendLine("body{background:#1e1e1e;color:#d4d4d4;font-family:Consolas,monospace;padding:20px}");
            h.AppendLine("h1{color:#569cd6;font-size:20px;margin-bottom:8px}");
            h.AppendLine(".info{color:#888;font-size:13px;margin-bottom:16px}");
            h.AppendLine("table{border-collapse:collapse;width:100%}");
            h.AppendLine("td{padding:0 12px;white-space:pre;font-size:14px;line-height:1.7;vertical-align:top}");
            h.AppendLine("tr:hover{background:#2a2a2a}");
            h.AppendLine(".ln{color:#555;text-align:right;user-select:none;width:40px;padding-right:16px}");
            h.AppendLine(".tag{color:#569cd6}");
            h.AppendLine(".atn{color:#9cdcfe}");
            h.AppendLine(".atv{color:#ce9178}");
            h.AppendLine(".cmt{color:#6a9955;font-style:italic}");
            h.AppendLine(".pnc{color:#808080}");
            h.AppendLine(".kw{color:#c586c0}");
            h.AppendLine("</style></head><body>");
            h.AppendLine("<h1>URDF Viewer</h1>");
            h.AppendLine("<div class=\"info\">robot_stl.urdf</div>");
            h.AppendLine("<table><tbody>");

            // 줄 단위 파싱 + 하이라이팅
            string[] lines = urdfXml.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            for (int i = 0; i < lines.Length; i++)
            {
                string line = lines[i];
                if (line.TrimEnd().Length == 0 && i == lines.Length - 1) break; // 마지막 빈줄 스킵

                h.AppendFormat("<tr><td class=\"ln\">{0}</td><td>", i + 1);
                h.Append(ColorizeXmlLine(line));
                h.AppendLine("</td></tr>");
            }

            h.AppendLine("</tbody></table></body></html>");

            File.WriteAllText(htmlPath, h.ToString(), Encoding.UTF8);
            try { Process.Start(htmlPath); } catch { }
        }

        /// <summary>XML 한 줄을 HTML 구문 하이라이팅</summary>
        private static string ColorizeXmlLine(string line)
        {
            StringBuilder sb = new StringBuilder();
            int pos = 0;
            int len = line.Length;

            while (pos < len)
            {
                // 주석: <!-- ... -->
                if (pos + 3 < len && line[pos] == '<' && line[pos + 1] == '!'
                    && line[pos + 2] == '-' && line[pos + 3] == '-')
                {
                    int end = line.IndexOf("-->", pos + 4);
                    if (end < 0) end = len - 3;
                    string comment = line.Substring(pos, end + 3 - pos);
                    sb.AppendFormat("<span class=\"cmt\">{0}</span>", Esc(comment));
                    pos = end + 3;
                    continue;
                }

                // XML 선언: <?xml ... ?>
                if (pos + 1 < len && line[pos] == '<' && line[pos + 1] == '?')
                {
                    int end = line.IndexOf("?>", pos + 2);
                    if (end < 0) end = len - 2;
                    string decl = line.Substring(pos, end + 2 - pos);
                    sb.AppendFormat("<span class=\"kw\">{0}</span>", Esc(decl));
                    pos = end + 2;
                    continue;
                }

                // 닫는 태그: </tagname>
                if (pos + 1 < len && line[pos] == '<' && line[pos + 1] == '/')
                {
                    int end = line.IndexOf('>', pos + 2);
                    if (end < 0) end = len - 1;
                    string tagName = line.Substring(pos + 2, end - pos - 2).Trim();
                    sb.AppendFormat("<span class=\"pnc\">&lt;/</span><span class=\"tag\">{0}</span><span class=\"pnc\">&gt;</span>",
                        Esc(tagName));
                    pos = end + 1;
                    continue;
                }

                // 여는 태그: <tagname attr="val" ...> 또는 <tagname ... />
                if (line[pos] == '<' && pos + 1 < len && char.IsLetter(line[pos + 1]))
                {
                    // 태그 이름 추출
                    int nameStart = pos + 1;
                    int nameEnd = nameStart;
                    while (nameEnd < len && !char.IsWhiteSpace(line[nameEnd])
                           && line[nameEnd] != '>' && line[nameEnd] != '/')
                        nameEnd++;

                    string tagName = line.Substring(nameStart, nameEnd - nameStart);
                    sb.AppendFormat("<span class=\"pnc\">&lt;</span><span class=\"tag\">{0}</span>", Esc(tagName));

                    pos = nameEnd;

                    // 속성 파싱
                    while (pos < len && line[pos] != '>' && !(line[pos] == '/' && pos + 1 < len && line[pos + 1] == '>'))
                    {
                        // 공백 건너뛰기
                        if (char.IsWhiteSpace(line[pos]))
                        {
                            sb.Append(line[pos]);
                            pos++;
                            continue;
                        }

                        // 속성이름=값
                        if (char.IsLetter(line[pos]) || line[pos] == '_')
                        {
                            int aStart = pos;
                            while (pos < len && line[pos] != '=' && line[pos] != '>'
                                   && !char.IsWhiteSpace(line[pos]) && line[pos] != '/')
                                pos++;
                            string attrName = line.Substring(aStart, pos - aStart);
                            sb.AppendFormat("<span class=\"atn\">{0}</span>", Esc(attrName));

                            // = 부호
                            if (pos < len && line[pos] == '=')
                            {
                                sb.Append("<span class=\"pnc\">=</span>");
                                pos++;

                                // 값 (따옴표)
                                if (pos < len && (line[pos] == '"' || line[pos] == '\''))
                                {
                                    char q = line[pos];
                                    int vEnd = line.IndexOf(q, pos + 1);
                                    if (vEnd < 0) vEnd = len - 1;
                                    string val = line.Substring(pos, vEnd + 1 - pos);
                                    sb.AppendFormat("<span class=\"atv\">{0}</span>", Esc(val));
                                    pos = vEnd + 1;
                                }
                            }
                            continue;
                        }

                        // 기타 문자
                        sb.Append(Esc(line[pos].ToString()));
                        pos++;
                    }

                    // 자기닫기 /> 또는 >
                    if (pos < len && line[pos] == '/' && pos + 1 < len && line[pos + 1] == '>')
                    {
                        sb.Append("<span class=\"pnc\">/&gt;</span>");
                        pos += 2;
                    }
                    else if (pos < len && line[pos] == '>')
                    {
                        sb.Append("<span class=\"pnc\">&gt;</span>");
                        pos++;
                    }
                    continue;
                }

                // 텍스트 내용 (태그 밖)
                int nextTag = line.IndexOf('<', pos);
                if (nextTag < 0) nextTag = len;
                if (nextTag > pos)
                {
                    sb.Append(Esc(line.Substring(pos, nextTag - pos)));
                    pos = nextTag;
                }
                else
                {
                    sb.Append(Esc(line[pos].ToString()));
                    pos++;
                }
            }

            return sb.ToString();
        }

        private static string Esc(string s)
        {
            return s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\"", "&quot;");
        }

