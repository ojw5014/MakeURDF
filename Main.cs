        /// <summary>
        /// Fusion 360 스타일 면 선택: 마우스 위치에서 3D 레이를 쏘아
        /// STL 삼각형 히트 → 동일 법선 인접 삼각형으로 면 확장 → 빨간색 하이라이트.
        /// C3d 피킹 시스템 불필요 (독립적 레이캐스트).
        /// </summary>
        private bool TrySelectStlFace(int mouseX, int mouseY)
        {
            if (m_C3d == null) return false;

            // 정사영 레이 생성
            double wox, woy, woz, wdx, wdy, wdz;
            m_C3d.GetOrthoRay(mouseX, mouseY, pnDisp.Width, pnDisp.Height,
                out wox, out woy, out woz, out wdx, out wdy, out wdz);

            // 모든 STL 스텝에 대해 레이캐스트
            int bestStepIdx = -1;
            int bestTriIdx = -1;
            float bestT = float.MaxValue;
            StlBoundingBox bestBbox = null;
            float bestOffX = 0, bestOffY = 0, bestOffZ = 0;
            float bestPan = 0, bestTilt = 0, bestSwing = 0;

            for (int i = 0; i < m_Builder.StepCount; i++)
            {
                DhStep step = m_Builder.GetStep(i);
                if (step.Action != BuildAction.Stl) continue;

                string dhLine = step.DhLines.TrimStart('@');
                string[] parts = dhLine.Split(',');
                if (parts.Length < 1) continue;
                string stlFilename = parts[0].Trim();

                string stlPath = Path.Combine(Application.StartupPath, "stl", stlFilename);
                StlBoundingBox bbox;
                try { bbox = StlParser.Parse(stlPath); }
                catch { continue; }
                if (!bbox.IsValid) continue;

                float offX = 0, offY = 0, offZ = 0;
                float stlPan = 0, stlTilt = 0, stlSwing = 0;
                if (parts.Length >= 8)
                {
                    float.TryParse(parts[5], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out offX);
                    float.TryParse(parts[6], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out offY);
                    float.TryParse(parts[7], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out offZ);
                }
                if (parts.Length >= 11)
                {
                    float.TryParse(parts[8], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out stlPan);
                    float.TryParse(parts[9], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out stlTilt);
                    float.TryParse(parts[10], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out stlSwing);
                }

                // 레이를 STL 로컬 좌표계로 변환
                // 렌더링: DH_chain * Translate(off) * Rz(swing) * Rx(tilt) * Ry(pan) * vertex
                // 역변환: Ry(-pan) * Rx(-tilt) * Rz(-swing) * (Re^T * (ray - endpoint) - offset)
                double epx, epy, epz;
                m_Builder.GetEndpointPosition(i, out epx, out epy, out epz);
                double[,] Re = m_Builder.GetEndpointRotation(i);

                double dxw = wox - epx, dyw = woy - epy, dzw = woz - epz;

                // Re^T * (ray - endpoint) - offset → endpoint 로컬 좌표
                float eox = (float)(Re[0, 0] * dxw + Re[1, 0] * dyw + Re[2, 0] * dzw) - offX;
                float eoy = (float)(Re[0, 1] * dxw + Re[1, 1] * dyw + Re[2, 1] * dzw) - offY;
                float eoz = (float)(Re[0, 2] * dxw + Re[1, 2] * dyw + Re[2, 2] * dzw) - offZ;

                float edx = (float)(Re[0, 0] * wdx + Re[1, 0] * wdy + Re[2, 0] * wdz);
                float edy = (float)(Re[0, 1] * wdx + Re[1, 1] * wdy + Re[2, 1] * wdz);
                float edz = (float)(Re[0, 2] * wdx + Re[1, 2] * wdy + Re[2, 2] * wdz);

                // STL 회전 역변환: Rm^T * (endpoint_local)
                // Rm = Rz(swing) * Rx(tilt) * Ry(pan) (OjwRotation 적용 순서)
                float lox = eox, loy = eoy, loz = eoz;
                float ldx = edx, ldy = edy, ldz = edz;
                if (stlSwing != 0 || stlTilt != 0 || stlPan != 0)
                {
                    double[,] Rm = DhBuilder.StlLocalRotation(stlPan, stlTilt, stlSwing);
                    // Rm^T * vector
                    lox = (float)(Rm[0, 0] * eox + Rm[1, 0] * eoy + Rm[2, 0] * eoz);
                    loy = (float)(Rm[0, 1] * eox + Rm[1, 1] * eoy + Rm[2, 1] * eoz);
                    loz = (float)(Rm[0, 2] * eox + Rm[1, 2] * eoy + Rm[2, 2] * eoz);
                    ldx = (float)(Rm[0, 0] * edx + Rm[1, 0] * edy + Rm[2, 0] * edz);
                    ldy = (float)(Rm[0, 1] * edx + Rm[1, 1] * edy + Rm[2, 1] * edz);
                    ldz = (float)(Rm[0, 2] * edx + Rm[1, 2] * edy + Rm[2, 2] * edz);
                }

                int hitTri = StlParser.RaycastMesh(bbox, lox, loy, loz, ldx, ldy, ldz);
                if (hitTri < 0) continue;

                // 히트 거리 계산 (여러 STL 간 비교용)
                int b = hitTri * 9;
                float t = StlParser.RayTriangleIntersect(lox, loy, loz, ldx, ldy, ldz,
                    bbox.Vertices[b], bbox.Vertices[b + 1], bbox.Vertices[b + 2],
                    bbox.Vertices[b + 3], bbox.Vertices[b + 4], bbox.Vertices[b + 5],
                    bbox.Vertices[b + 6], bbox.Vertices[b + 7], bbox.Vertices[b + 8]);

                if (t < bestT)
                {
                    bestT = t;
                    bestStepIdx = i;
                    bestTriIdx = hitTri;
                    bestBbox = bbox;
                    bestOffX = offX;
                    bestOffY = offY;
                    bestOffZ = offZ;
                    bestPan = stlPan;
                    bestTilt = stlTilt;
                    bestSwing = stlSwing;
                }
            }

            if (bestStepIdx < 0) return false;

            // 히스토리에서 해당 항목 선택
            if (bestStepIdx < lstHistory.Items.Count)
                lstHistory.SelectedIndex = bestStepIdx;

            // 동일 법선 인접 삼각형으로 면 확장 (Fusion 360 스타일)
            List<int> faceTris = StlParser.FloodFillFace(bestBbox, bestTriIdx);
            if (faceTris.Count == 0) return false;

            // 구멍 근처 클릭 시 구멍 경계 삼각형만 분리
            faceTris = StlParser.FilterHoleNearbyTris(bestBbox, faceTris, bestTriIdx);

            // 하이라이트 STL 파일 생성
            string hlName = "_highlight.stl";
            string highlightPath = Path.Combine(Application.StartupPath, "stl", hlName);
            m_C3d.OjwAse_InvalidateCache(hlName);

            int triCount = StlParser.WriteClusterStl(bestBbox, faceTris, highlightPath);

            if (triCount > 0)
            {
                string overlayLine = string.Format(
                    System.Globalization.CultureInfo.InvariantCulture,
                    "@{0},16711680,1.0,9,0,{1:F3},{2:F3},{3:F3},{4:F1},{5:F1},{6:F1}",
                    hlName, bestOffX, bestOffY, bestOffZ, bestPan, bestTilt, bestSwing);
                m_Builder.SetOverlay(bestStepIdx, overlayLine);
            }

            // 면 중심 및 법선 저장 (btnStlCenter에서 사용)
            float cx, cy, cz;
            StlParser.GetClusterCentroid(bestBbox, faceTris, out cx, out cy, out cz);

            float nx, ny, nz;
            StlParser.GetTriangleNormal(bestBbox, bestTriIdx, out nx, out ny, out nz);

            m_nSelectedStlFace = DhBuilder.DetermineBBFace(nx, ny, nz);
            m_fSelectedFaceCenterX = cx;
            m_fSelectedFaceCenterY = cy;
            m_fSelectedFaceCenterZ = cz;
            m_fSelectedFaceNormalX = nx;
            m_fSelectedFaceNormalY = ny;
            m_fSelectedFaceNormalZ = nz;
            m_nSelectedStlHistoryIdx = bestStepIdx;
            m_lstSelectedFaceTris = faceTris;
            m_SelectedFaceBbox = bestBbox;

            DhStep hitStep = m_Builder.GetStep(bestStepIdx);
            string filename = hitStep.DhLines.TrimStart('@').Split(',')[0].Trim();

            UpdatePreview(null, true);
            lblStatus.Text = string.Format("{0} → 면 선택 ({1}개 삼각형)", filename, triCount);
            lblCurrentValue.Text = string.Format("중심 ({0:F1}, {1:F1}, {2:F1})", cx, cy, cz);
            return true;
        }

        /// <summary>
        /// 마우스 호버 시 STL 면의 경계 에지를 표시.
        /// TrySelectStlFace와 동일한 레이캐스트 후 에지 하이라이트 STL 생성.
        /// </summary>
        private void TryHoverStlFace(int mouseX, int mouseY)
        {
            if (m_C3d == null) return;

            // 정사영 레이 생성
            double wox, woy, woz, wdx, wdy, wdz;
            m_C3d.GetOrthoRay(mouseX, mouseY, pnDisp.Width, pnDisp.Height,
                out wox, out woy, out woz, out wdx, out wdy, out wdz);

            // 디버그: 레이-바닥면(Z=0) 교차점을 십자선 위치로 저장
            if (Math.Abs(wdz) > 1e-6)
            {
                double tHit = -woz / wdz;
                m_fDbgWorldX = (float)(wox + wdx * tHit);
                m_fDbgWorldY = (float)(woy + wdy * tHit);
                m_fDbgWorldZ = 0;
                m_bDbgShowCrosshair = true;
            }

            int bestStepIdx = -1;
            int bestTriIdx = -1;
            float bestT = float.MaxValue;
            StlBoundingBox bestBbox = null;
            float bestOffX = 0, bestOffY = 0, bestOffZ = 0;
            float bestPan = 0, bestTilt = 0, bestSwing = 0;

            for (int i = 0; i < m_Builder.StepCount; i++)
            {
                DhStep step = m_Builder.GetStep(i);
                if (step.Action != BuildAction.Stl) continue;

                string dhLine = step.DhLines.TrimStart('@');
                string[] parts = dhLine.Split(',');
                if (parts.Length < 1) continue;
                string stlFilename = parts[0].Trim();

                string stlPath = Path.Combine(Application.StartupPath, "stl", stlFilename);
                StlBoundingBox bbox;
                try { bbox = StlParser.Parse(stlPath); }
                catch { continue; }
                if (!bbox.IsValid) continue;

                float offX = 0, offY = 0, offZ = 0;
                float stlPan = 0, stlTilt = 0, stlSwing = 0;
                if (parts.Length >= 8)
                {
                    float.TryParse(parts[5], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out offX);
                    float.TryParse(parts[6], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out offY);
                    float.TryParse(parts[7], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out offZ);
                }
                if (parts.Length >= 11)
                {
                    float.TryParse(parts[8], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out stlPan);
                    float.TryParse(parts[9], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out stlTilt);
                    float.TryParse(parts[10], System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out stlSwing);
                }

                double epx, epy, epz;
                m_Builder.GetEndpointPosition(i, out epx, out epy, out epz);
                double[,] Re = m_Builder.GetEndpointRotation(i);

                double dxw2 = wox - epx, dyw2 = woy - epy, dzw2 = woz - epz;

                // Re^T * (ray - endpoint) - offset → endpoint 로컬 좌표
                float eox = (float)(Re[0, 0] * dxw2 + Re[1, 0] * dyw2 + Re[2, 0] * dzw2) - offX;
                float eoy = (float)(Re[0, 1] * dxw2 + Re[1, 1] * dyw2 + Re[2, 1] * dzw2) - offY;
                float eoz = (float)(Re[0, 2] * dxw2 + Re[1, 2] * dyw2 + Re[2, 2] * dzw2) - offZ;

                float edx = (float)(Re[0, 0] * wdx + Re[1, 0] * wdy + Re[2, 0] * wdz);
                float edy = (float)(Re[0, 1] * wdx + Re[1, 1] * wdy + Re[2, 1] * wdz);
                float edz = (float)(Re[0, 2] * wdx + Re[1, 2] * wdy + Re[2, 2] * wdz);

                // STL 회전 역변환: Rm^T * (endpoint_local)
                float lox = eox, loy = eoy, loz = eoz;
                float ldx = edx, ldy = edy, ldz = edz;
                if (stlSwing != 0 || stlTilt != 0 || stlPan != 0)
                {
                    double[,] Rm = DhBuilder.StlLocalRotation(stlPan, stlTilt, stlSwing);
                    lox = (float)(Rm[0, 0] * eox + Rm[1, 0] * eoy + Rm[2, 0] * eoz);
                    loy = (float)(Rm[0, 1] * eox + Rm[1, 1] * eoy + Rm[2, 1] * eoz);
                    loz = (float)(Rm[0, 2] * eox + Rm[1, 2] * eoy + Rm[2, 2] * eoz);
                    ldx = (float)(Rm[0, 0] * edx + Rm[1, 0] * edy + Rm[2, 0] * edz);
                    ldy = (float)(Rm[0, 1] * edx + Rm[1, 1] * edy + Rm[2, 1] * edz);
                    ldz = (float)(Rm[0, 2] * edx + Rm[1, 2] * edy + Rm[2, 2] * edz);
                }

                int hitTri = StlParser.RaycastMesh(bbox, lox, loy, loz, ldx, ldy, ldz);
                if (hitTri < 0) continue;

                int b = hitTri * 9;
                float t = StlParser.RayTriangleIntersect(lox, loy, loz, ldx, ldy, ldz,
                    bbox.Vertices[b], bbox.Vertices[b + 1], bbox.Vertices[b + 2],
                    bbox.Vertices[b + 3], bbox.Vertices[b + 4], bbox.Vertices[b + 5],
                    bbox.Vertices[b + 6], bbox.Vertices[b + 7], bbox.Vertices[b + 8]);

                if (t < bestT)
                {
                    bestT = t;
                    bestStepIdx = i;
                    bestTriIdx = hitTri;
                    bestBbox = bbox;
                    bestOffX = offX;
                    bestOffY = offY;
                    bestOffZ = offZ;
                    bestPan = stlPan;
                    bestTilt = stlTilt;
                    bestSwing = stlSwing;
                }
            }

            if (bestStepIdx < 0)
            {
                // 히트 없음 → 호버 해제 + 십자선 갱신
                bool needRefresh = m_bHoverActive || m_bDbgShowCrosshair;
                if (m_bHoverActive)
                    m_Builder.ClearOverlay();
                m_bHoverActive = false;
                if (needRefresh)
                    UpdatePreview(null);
                return;
            }

            List<int> faceTris = StlParser.FloodFillFace(bestBbox, bestTriIdx);
            if (faceTris.Count == 0) return;

            // 구멍 근처 호버 시 구멍 경계 삼각형만 분리
            faceTris = StlParser.FilterHoleNearbyTris(bestBbox, faceTris, bestTriIdx);

            float nx, ny, nz;
            StlParser.GetTriangleNormal(bestBbox, bestTriIdx, out nx, out ny, out nz);

            // 에지 하이라이트 STL 생성
            string edgeName = "_hover_edge.stl";
            string edgePath = Path.Combine(Application.StartupPath, "stl", edgeName);
            m_C3d.OjwAse_InvalidateCache(edgeName);

            int edgeCount = StlParser.WriteEdgeHighlightStl(bestBbox, faceTris, edgePath, nx, ny, nz);
            if (edgeCount > 0)
            {
                // 시안(cyan) 색상 = 65535 (0x00FFFF)
                string overlayLine = string.Format(
                    System.Globalization.CultureInfo.InvariantCulture,
                    "@{0},65535,1.0,9,0,{1:F3},{2:F3},{3:F3},{4:F1},{5:F1},{6:F1}",
                    edgeName, bestOffX, bestOffY, bestOffZ, bestPan, bestTilt, bestSwing);
                m_Builder.SetOverlay(bestStepIdx, overlayLine);
                m_bHoverActive = true;
                UpdatePreview(null, true);
            }
        }

