        /// <summary>
        /// STL 파일을 stl/ 폴더로 복사하고 실제 저장된 파일명 반환
        /// </summary>
        private string CopyStlToFolder(string srcPath)
        {
            string stlDir = Path.Combine(Application.StartupPath, "stl");
            if (!Directory.Exists(stlDir))
                Directory.CreateDirectory(stlDir);
            string destName = Path.GetFileName(srcPath);
            string destPath = Path.Combine(stlDir, destName);
            string srcFull = Path.GetFullPath(srcPath);
            string dstFull = Path.GetFullPath(destPath);

            // 소스가 이미 stl 폴더에 있으면 복사 불필요
            if (srcFull.Equals(dstFull, StringComparison.OrdinalIgnoreCase))
                return destName;

            try
            {
                File.Copy(srcPath, destPath, true);
            }
            catch (IOException)
            {
                // C3d가 파일을 잡고 있으면 다른 이름으로 복사
                string nameOnly = Path.GetFileNameWithoutExtension(destName);
                string ext = Path.GetExtension(destName);
                bool copied = false;
                for (int i = 1; i < 100; i++)
                {
                    destName = string.Format("{0}_{1}{2}", nameOnly, i, ext);
                    destPath = Path.Combine(stlDir, destName);
                    try
                    {
                        File.Copy(srcPath, destPath, true);
                        copied = true;
                        break;
                    }
                    catch (IOException) { }
                }
                if (!copied) throw;
            }
            return destName;
        }

        /// <summary>
        /// STL 면 하이라이트 (레이캐스트 위임). btnStlCenter 등에서 호출.
