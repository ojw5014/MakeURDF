                if (m_bMergeMode)
                {
                    ExitMergeMode();
                    return true;
                }
                if (m_bDragging)
                {
                    CancelDrag();
                    return true;
                }
            }
            return base.ProcessCmdKey(ref msg, keyData);
        }

