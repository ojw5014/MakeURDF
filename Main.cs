        /// <summary>
        /// DH 텍스트에서 robot_config.txt 내용을 생성
        /// </summary>
        private string BuildRobotConfigText(string dhString)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("# robot_config.txt");
            sb.AppendLine("# Generated by MakeUrdf");
            sb.AppendLine("# DH Convention: [A,D,Theta,Alpha],[Axis,Dir,Init]");
            sb.AppendLine("# A=링크길이(mm), D=오프셋(mm), Theta=각도(deg), Alpha=비틀림(deg)");
            sb.AppendLine("# Axis=모터ID(-1:없음), Dir=방향(0:+Z회전,1:-Z회전,2:+Z이동,3:-Z이동)");
            sb.AppendLine("# Init=1이면 새 체인 시작 (좌표 리셋)");
            sb.AppendLine();

            // 모터 ID 추출 (유니크, 순서 유지)
            List<int> motorIds = ExtractMotorIds(dhString);

            // 손목 경계 모터 ID (-1이면 없음 = 전체 팔)
            int wristMotorId = GetSelectedWristMotorId();

            // 그리퍼 모터 ID (-1이면 없음)
            int gripperMotorId = GetSelectedGripperMotorId();

            sb.AppendLine("[INFO]");
            sb.AppendLine("name=robot");
            sb.AppendLine(string.Format("wrist_boundary_id={0}", wristMotorId));
            if (gripperMotorId >= 0)
                sb.AppendLine(string.Format("gripper_ids={0}", gripperMotorId));
            sb.AppendLine();

            sb.AppendLine("[MOTORS]");
            sb.AppendLine(string.Join(",", motorIds.ConvertAll(m => m.ToString()).ToArray()));
            sb.AppendLine();

            sb.AppendLine("[DH]");
            // DH 라인만 추출 (@, #, 빈줄, 순수주석 제거)
            string[] lines = dhString.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            foreach (string rawLine in lines)
            {
                string trimmed = rawLine.Trim();
                if (trimmed.Length == 0) continue;
                if (trimmed.StartsWith("@")) continue;   // STL 모델 라인 제외
                if (trimmed.StartsWith("#")) continue;   // 함수 번호 제외
                if (trimmed.StartsWith("//")) continue;  // 순수 주석 제외

                sb.AppendLine(trimmed);
            }

            return sb.ToString();
        }

        /// <summary>DH 텍스트에서 유니크 모터 ID 목록 추출 (순서 유지)</summary>
        private List<int> ExtractMotorIds(string dhString)
        {
            List<int> ids = new List<int>();
            HashSet<int> seen = new HashSet<int>();

            string[] lines = dhString.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            foreach (string rawLine in lines)
            {
                string line = rawLine.Trim();
                if (line.Length == 0 || line.StartsWith("@") || line.StartsWith("#") || line.StartsWith("//"))
                    continue;

                // 인라인 주석 제거
                int cp = line.IndexOf("//");
                if (cp >= 0) line = line.Substring(0, cp);

                line = line.Replace("[", "").Replace("]", "").Trim();
                string[] parts = line.Split(',');
                if (parts.Length < 5) continue;

                int axis;
                if (!int.TryParse(parts[4].Trim(), out axis)) continue;
                if (axis < 0) continue;

                if (!seen.Contains(axis))
                {
                    seen.Add(axis);
                    ids.Add(axis);
                }
            }
            return ids;
        }

