        // ========================================
        // 하이브리드 드래그 핸들러 (pnDragArea)
        // ========================================
        private void pnDragArea_MouseDown(object sender, MouseEventArgs e)
        {
            if (m_eMode != InteractionMode.Hybrid) return;
            if (e.Button != MouseButtons.Left) return;

            if (m_eCurrentAction == BuildAction.None)
            {
                lblStatus.Text = "먼저 축 버튼을 선택하세요!";
                return;
            }

            m_bDragging = true;
            m_nDragStartX = e.X;
            m_TempStep = null;

            // STL 선택 상태면 STL 드래그 시작
            int stlIdx = GetSelectedStlStepIndex();
            if (stlIdx >= 0)
                BeginStlDrag(stlIdx);
            else
                m_nStlDragStepIdx = -1;
        }

        private void pnDragArea_MouseMove(object sender, MouseEventArgs e)
        {
            if (!m_bDragging || m_eMode != InteractionMode.Hybrid) return;

            int dx = e.X - m_nDragStartX;
            float value = (float)Math.Round(dx * m_fDragSensitivity);

            // STL 드래그 중이면 STL 파라미터 수정
            if (m_nStlDragStepIdx >= 0)
            {
                UpdateStlDrag(m_eCurrentAction, value);
            }
            else
            {
                m_TempStep = DhBuilder.CreateStep(m_eCurrentAction, value);
                UpdatePreview(m_TempStep);
            }

            bool isRot = DhBuilder.IsRotation(m_eCurrentAction);
            string unit = isRot ? "도" : "mm";
            string prefix = (m_nStlDragStepIdx >= 0) ? "STL " : "";
            lblStatus.Text = prefix + DhBuilder.GetAxisName(m_eCurrentAction);
            lblCurrentValue.Text = string.Format("{0}{1}", (int)value, unit);
        }

        private void pnDragArea_MouseUp(object sender, MouseEventArgs e)
        {
            if (!m_bDragging || m_eMode != InteractionMode.Hybrid) return;

            // STL 드래그 완료
            if (m_nStlDragStepIdx >= 0)
            {
                int dx = e.X - m_nDragStartX;
                float finalDelta = (float)Math.Round(dx * m_fDragSensitivity);
                EndStlDrag(m_eCurrentAction, finalDelta);
                RefreshHistory();
                if (finalDelta != 0)
                    lblStatus.Text = string.Format("STL {0} {1:+0;-0}{2}", DhBuilder.GetAxisName(m_eCurrentAction),
                        finalDelta, DhBuilder.IsRotation(m_eCurrentAction) ? "도" : "mm");
                else
                    lblStatus.Text = "STL 드래그 취소";
            }
            else if (m_TempStep != null && m_TempStep.Value != 0)
            {
                m_Builder.AddStep(m_TempStep);
                RefreshHistory();
                lblStatus.Text = m_TempStep.Description + " 추가!";
            }
            else
            {
                lblStatus.Text = "드래그 영역을 드래그하세요 (" + DhBuilder.GetAxisName(m_eCurrentAction) + ")";
            }

            m_bDragging = false;
            m_TempStep = null;
            // 하이브리드 모드: 축 선택 유지 (연속 드래그 가능)
            UpdatePreview(null);
        }

