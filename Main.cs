        private int GetSelectedStlStepIndex()
        {
            int idx = lstHistory.SelectedIndex;
            if (idx < 0 || idx >= m_Builder.StepCount) return -1;
            if (m_Builder.GetStep(idx).Action != BuildAction.Stl) return -1;
