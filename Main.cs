        // ========================================
        // 3D 마우스 드래그 핸들러 (마우스 모드 전용)
        // ========================================
        private void OnC3dMouseDown(object sender, MouseEventArgs e)
        {
            if (e.Button == MouseButtons.Left)
            {
                m_nLastClickX = e.X;
                m_nLastClickY = e.Y;
                // 피킹 트리거: 좌클릭으로 축 핸들 선택
                m_C3d.SetPickCheck_OneShot(e.X, e.Y);
            }

            if (m_eMode != InteractionMode.Mouse) return;
            if (e.Button != MouseButtons.Left) return;

            // STL 선택 상태면 STL 드래그 시작 (merge 모드일 때는 면 클릭이므로 드래그 안 함)
            int stlIdx = GetSelectedStlStepIndex();
            if (stlIdx >= 0 && !m_bMergeMode)
            {
                m_bDragging = true;
                m_nDragStartX = e.X;
                m_nDragStartY = e.Y;
                m_eAutoDetectedAction = BuildAction.None;
                m_TempStep = null;
                BeginStlDrag(stlIdx);
            }
            else
            {
                m_nStlDragStepIdx = -1;
            }
        }

        private void OnC3dMouseMove(object sender, MouseEventArgs e)
        {
            // STL 면 호버 프리뷰 (결합 모드: 버튼 안 눌렀을 때)
            if (m_bMergeMode && e.Button == MouseButtons.None)
            {
                int hdx = e.X - m_nLastHoverX;
                int hdy = e.Y - m_nLastHoverY;
                if (hdx * hdx + hdy * hdy > 36)
                {
                    m_nLastHoverX = e.X;
                    m_nLastHoverY = e.Y;
                    TryHoverStlFace(e.X, e.Y);
                }
                return;
            }

            // STL 드래그만 처리 (DH 파라미터 생성은 클릭+휠 방식으로 변경)
            if (!m_bDragging || m_eMode != InteractionMode.Mouse || m_nStlDragStepIdx < 0) return;

            int dx = e.X - m_nDragStartX;
            int dy = e.Y - m_nDragStartY;

            BuildAction action = m_eCurrentAction != BuildAction.None
                ? m_eCurrentAction
                : m_C3d.DetectAxisFromDrag(m_Builder, dx, dy);

            float value = (float)Math.Round(m_C3d.GetAxisDelta(m_Builder, action, dx, dy, m_fDragSensitivity));
            UpdateStlDrag(action, value);

            bool isRot = DhBuilder.IsRotation(action);
            lblStatus.Text = "STL " + DhBuilder.GetAxisName(action);
            lblCurrentValue.Text = string.Format("{0}{1}", (int)value, isRot ? "도" : "mm");
        }

        private void OnC3dMouseUp(object sender, MouseEventArgs e)
        {
            // STL 면 선택 (모든 모드): 클릭(드래그 아닌) 시 레이캐스트로 면 감지
            bool stlSelected = false;
            if (e.Button == MouseButtons.Left)
            {
                int adx = Math.Abs(e.X - m_nLastClickX);
                int ady = Math.Abs(e.Y - m_nLastClickY);
                if (adx < 5 && ady < 5)
                {
                    stlSelected = TrySelectStlFace(e.X, e.Y);
                    if (stlSelected && m_bMergeMode)
                    {
                        HandleMergeClick();
                        // merge 처리 후 STL 드래그 취소 (EndStlDrag가 DhLines 덮어쓰기 방지)
                        m_nStlDragStepIdx = -1;
                        m_strStlOriginalDhLines = "";
                    }
                }
            }

            if (!m_bDragging || m_eMode != InteractionMode.Mouse) return;

            // STL 드래그 완료
            if (m_nStlDragStepIdx >= 0)
            {
                BuildAction action = m_eCurrentAction != BuildAction.None ? m_eCurrentAction : m_eAutoDetectedAction;
                int dx = e.X - m_nDragStartX;
                int dy = e.Y - m_nDragStartY;
                float finalDelta = action != BuildAction.None ? (float)Math.Round(m_C3d.GetAxisDelta(m_Builder, action, dx, dy, m_fDragSensitivity)) : 0;
                EndStlDrag(action, finalDelta);
                RefreshHistory();
                UpdatePreview(null);
                lblStatus.Text = finalDelta != 0
                    ? string.Format("STL {0} {1:+0;-0}{2}", DhBuilder.GetAxisName(action), finalDelta, DhBuilder.IsRotation(action) ? "도" : "mm")
                    : "STL 드래그 취소";
            }

            m_bDragging = false;
            m_TempStep = null;
            m_eAutoDetectedAction = BuildAction.None;
        }

        // ========================================
        // 마우스 휠 핸들러
        // - 축 선택 후 스크롤       → 이동(translate)
        // - 축 선택 후 Ctrl+스크롤  → 회전(rotate)
        // - 축 미선택               → 줌
        // ========================================
        private void OnC3dMouseWheel(object sender, MouseEventArgs e)
        {
            if (m_eMode == InteractionMode.Mouse && m_eCurrentAction != BuildAction.None)
            {
                bool isCtrl = (Control.ModifierKeys & Keys.Control) != 0;
                // Move 액션을 기준으로 저장되어 있으므로 Ctrl이면 대응하는 Rotate 액션으로 변환
                BuildAction action = m_eCurrentAction;
                if (isCtrl)
                {
                    if (action == BuildAction.RedMove)   action = BuildAction.RedRotate;
                    else if (action == BuildAction.GreenMove) action = BuildAction.GreenRotate;
                    else if (action == BuildAction.BlueMove)  action = BuildAction.BlueRotate;
                }
                float delta = (e.Delta > 0) ? -5.0f : 5.0f;
                AccumulateWheelStep(action, delta);
            }
            else
            {
                // 줌
                float fData = (e.Delta > 0) ? -0.01f : 0.01f;
                float newScale = m_C3d.GetScale() + fData;
                if (newScale > 0) m_C3d.SetScale(newScale);
            }
        }

        // 연속 스크롤 누적: 같은 액션이면 마지막 스텝 값 수정, 다르면 새 스텝 추가
        private void AccumulateWheelStep(BuildAction action, float delta)
        {
            float totalVal = delta;
            if (m_Builder.StepCount > 0)
            {
                var last = m_Builder.GetStep(m_Builder.StepCount - 1);
                if (last.Action == action && !last.IsRaw)
                {
                    totalVal = last.Value + delta;
                    m_Builder.RemoveLastStep();
                }
            }
            if (totalVal != 0)
                m_Builder.AddStep(DhBuilder.CreateStep(action, totalVal));

            RefreshHistory();
            UpdatePreview(null);
            string unit = DhBuilder.IsRotation(action) ? "도" : "mm";
            lblStatus.Text    = string.Format("{0} {1:+0;-0}{2}", DhBuilder.GetAxisName(action), totalVal, unit);
            lblCurrentValue.Text = string.Format("{0}{1}", (int)totalVal, unit);
        }

