        /// <summary>
        /// STL 중심이동: 감지된 면의 중심을 DH 끝점에 맞춤
        /// </summary>
        private void btnStlCenter_Click(object sender, EventArgs e)
        {
            int idx = lstHistory.SelectedIndex;
            if (idx < 0)
            {
                MessageBox.Show("히스토리에서 STL 항목을 선택하세요.", "알림",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            DhStep step = m_Builder.GetStep(idx);
            if (step.Action != BuildAction.Stl)
            {
                MessageBox.Show("선택된 항목이 STL이 아닙니다.", "알림",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            // 면이 아직 감지되지 않았으면 지금 감지
            if (m_nSelectedStlHistoryIdx != idx || m_nSelectedStlFace < 0)
                HighlightStlFace(idx);

            if (m_nSelectedStlHistoryIdx != idx || m_nSelectedStlFace < 0)
                return;

            // 파일명 추출
            string stlFilename = step.DhLines.TrimStart('@').Split(',')[0].Trim();

            // 기존 회전값 보존
            string fnTmp; float oxTmp, oyTmp, ozTmp, curPan, curTilt, curSwing;
            DhBuilder.ParseStlParams(step.DhLines, out fnTmp, out oxTmp, out oyTmp, out ozTmp,
                out curPan, out curTilt, out curSwing);

            // 면 중심을 DH 끝점으로 이동하는 오프셋 적용 (회전은 유지)
            // 렌더링: T(offset) * Rm * vertex → offset = -Rm * face_center
            double[,] Rm = DhBuilder.StlLocalRotation(curPan, curTilt, curSwing);
            float offX = -(float)(Rm[0, 0] * m_fSelectedFaceCenterX + Rm[0, 1] * m_fSelectedFaceCenterY + Rm[0, 2] * m_fSelectedFaceCenterZ);
            float offY = -(float)(Rm[1, 0] * m_fSelectedFaceCenterX + Rm[1, 1] * m_fSelectedFaceCenterY + Rm[1, 2] * m_fSelectedFaceCenterZ);
            float offZ = -(float)(Rm[2, 0] * m_fSelectedFaceCenterX + Rm[2, 1] * m_fSelectedFaceCenterY + Rm[2, 2] * m_fSelectedFaceCenterZ);

            step.DhLines = DhBuilder.BuildStlDhLines(stlFilename, offX, offY, offZ,
                curPan, curTilt, curSwing);

            RefreshHistory();
            UpdatePreview(null);

            string[] faceNames = { "+X", "-X", "+Y", "-Y", "+Z", "-Z" };
            string faceName = m_nSelectedStlFace >= 0 && m_nSelectedStlFace < 6
                ? faceNames[m_nSelectedStlFace] : "";
            lblStatus.Text = string.Format("{0} → {1}면 중심이동 완료", stlFilename, faceName);
        }

