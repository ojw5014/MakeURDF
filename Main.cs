        /// <summary>
        /// 면 클릭 후 축 정렬 처리.
        /// TrySelectStlFace가 성공한 뒤 호출됨.
        /// 선택한 면의 경계에서 원형 특징을 찾아 그 중심으로,
        /// 없으면 면 중심으로 축 원점에 정렬.
        /// </summary>
        private void HandleMergeClick()
        {
            int stepIdx = m_nSelectedStlHistoryIdx;
            if (stepIdx < 0) return;

            DhStep step = m_Builder.GetStep(stepIdx);
            if (step.Action != BuildAction.Stl) return;

            string stlFilename = step.DhLines.TrimStart('@').Split(',')[0].Trim();

            // TrySelectStlFace에서 저장된 면 삼각형 사용
            if (m_lstSelectedFaceTris != null && m_lstSelectedFaceTris.Count >= 3
                && m_SelectedFaceBbox != null)
            {
                float[] circCenter = StlParser.FindCircularFeatureOnFace(
                    m_SelectedFaceBbox, m_lstSelectedFaceTris, 0.7f);

                if (circCenter != null)
                {
                    ApplyFaceAlignOffset(step, stlFilename,
                        circCenter[0], circCenter[1], circCenter[2],
                        "원형 특징 중심");
                    return;
                }
            }

            // 원형 특징 없음 → 면 중심 사용
            ApplyFaceAlignOffset(step, stlFilename,
                m_fSelectedFaceCenterX, m_fSelectedFaceCenterY, m_fSelectedFaceCenterZ,
                "면 중심");
        }

        /// <summary>
        /// STL 오프셋 적용: 지정된 중심점이 DH 축 원점에 오도록 이동
        /// </summary>
        private void ApplyFaceAlignOffset(DhStep step, string stlFilename,
            float centerX, float centerY, float centerZ, string centerType)
        {
            // 기존 회전값 보존
            string fnTmp; float oxTmp, oyTmp, ozTmp, curPan, curTilt, curSwing;
            DhBuilder.ParseStlParams(step.DhLines, out fnTmp, out oxTmp, out oyTmp, out ozTmp,
                out curPan, out curTilt, out curSwing);

            // 렌더링: T(offset) * Rm * vertex → offset = -Rm * center
            double[,] Rm = DhBuilder.StlLocalRotation(curPan, curTilt, curSwing);
            float offX = -(float)(Rm[0, 0] * centerX + Rm[0, 1] * centerY + Rm[0, 2] * centerZ);
            float offY = -(float)(Rm[1, 0] * centerX + Rm[1, 1] * centerY + Rm[1, 2] * centerZ);
            float offZ = -(float)(Rm[2, 0] * centerX + Rm[2, 1] * centerY + Rm[2, 2] * centerZ);

            step.DhLines = DhBuilder.BuildStlDhLines(stlFilename, offX, offY, offZ,
                curPan, curTilt, curSwing);

            // 정렬 모드 종료
            m_bMergeMode = false;
            m_bHoverActive = false;
            m_Builder.ClearOverlay();
            if (m_C3d != null)
                m_C3d.SetMouseMode(m_eMode == InteractionMode.Mouse ? 99 : 0);

            RefreshHistory();
            UpdatePreview(null);
            lblStatus.Text = string.Format("{0} → {1} 기준 축 정렬 완료", stlFilename, centerType);
            lblCurrentValue.Text = string.Format("({0:F1}, {1:F1}, {2:F1})", centerX, centerY, centerZ);
        }

