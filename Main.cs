        /// <summary>
        /// Kinematics python 뷰어 스크립트를 읽어서 release_dir 경로를 패치 후 실행.
        /// 원본 스크립트의 release_dir = os.path.join(script_dir, "..", "Release") 를
        /// 현재 실행 경로(URDF/STL이 있는 곳)로 교체한다.
        /// </summary>
        private bool RunPythonViewer(string scriptFilename)
        {
            string pythonDir = FindPythonDir();
            string scriptPath = Path.Combine(pythonDir, scriptFilename);

            Ojw.printf(txtLogHistory, "[Python] 스크립트 경로: {0}\r\n", scriptPath);

            if (!File.Exists(scriptPath))
            {
                Ojw.printf(txtLogHistory, "[Python] 오류: {0} 파일을 찾을 수 없습니다.\r\n", scriptFilename);
                Ojw.printf(txtLogHistory, "[Python] Kinematics/bin/python/ 폴더의 파일을 MakeUrdf/bin/python/ 에 복사해 주세요.\r\n");
                return false;
            }

            string code = File.ReadAllText(scriptPath, System.Text.Encoding.UTF8);

            // release_dir를 URDF 출력 폴더로 패치 (URDF, MJCF, STL 파일 위치)
            string releaseDir = GetUrdfOutputDir().Replace("\\", "/");
            code = code.Replace(
                "release_dir = os.path.join(script_dir, \"..\", \"Release\")",
                "release_dir = r\"" + releaseDir + "\"");

            // USE_FIXED_BASE를 직접 패치 (config 파일 의존 제거)
            string fixedBaseStr = chkFixedBase.Checked ? "True" : "False";
            code = code.Replace(
                "USE_FIXED_BASE = viewer_config['FIXED_BASE']",
                "USE_FIXED_BASE = " + fixedBaseStr);

            m_CPython.SetTextBox(txtLogHistory);
            m_CPython.SetDebugMode(false);
            m_CPython.Run(code);

            // 로그 탭으로 자동 전환
            tabRight.SelectedTab = tabHistory;

            return true;
        }

