        /// <summary>
        /// 3D 피킹 결과로 히스토리 항목 선택.
        /// PickGroup_B(nMotor)와 일치하는 모터/STL 스텝을 찾아 선택.
        /// </summary>
        private int SelectHistoryByPickGroup(int nMotor)
        {
            if (nMotor < 0) return -1;

            // PickGroup은 모터 번호 기준으로 할당됨
            // 각 스텝이 어떤 모터 그룹에 속하는지 추적
            int currentGroup = -1;
            int bestIdx = -1;
            for (int i = 0; i < m_Builder.StepCount; i++)
            {
                var step = m_Builder.GetStep(i);
                if (step.Action == BuildAction.Motor)
                    currentGroup = step.MotorNumber;

                // 현재 그룹이 클릭된 그룹과 일치하는 스텝 중 마지막 것 선택
                if (currentGroup == nMotor)
                    bestIdx = i;
            }

            if (bestIdx >= 0 && bestIdx < lstHistory.Items.Count)
            {
                lstHistory.SelectedIndex = bestIdx;
                var step = m_Builder.GetStep(bestIdx);
                lblStatus.Text = string.Format("선택: [{0}] {1}", bestIdx + 1, step.Description);
            }
            return bestIdx;
        }

