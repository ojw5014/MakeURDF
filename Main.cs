        /// <summary>DH 텍스트를 Init=1 기준으로 그룹 분리</summary>
        private List<DhGroup> SplitDhByInit(string dhText)
        {
            string[] allLines = dhText.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            List<DhGroup> groups = new List<DhGroup>();
            List<string> currentLines = new List<string>();
            List<string> groupComments = new List<string>();
            int groupStartLine = 0;

            for (int i = 0; i < allLines.Length; i++)
            {
                string line = allLines[i].Trim();
                if (line.Length == 0) continue;
                if (line.StartsWith("//"))
                {
                    groupComments.Add(line);
                    continue;
                }

                // Init 값 확인
                string s = line;
                int cp = s.IndexOf("//");
                string lineComment = "";
                if (cp >= 0) { lineComment = s.Substring(cp + 2).Trim(); s = s.Substring(0, cp); }
                s = s.Replace("[", "").Replace("]", "").Trim();
                string[] parts = s.Split(',');
                int nInit = 0;
                if (parts.Length >= 7) int.TryParse(parts[6].Trim(), out nInit);

                if (nInit == 1 && currentLines.Count > 0)
                {
                    // 이전 그룹 저장
                    DhGroup prev = new DhGroup();
                    prev.GroupIndex = groups.Count;
                    prev.DhText = string.Join("\r\n", currentLines.ToArray());
                    prev.StartTextLine = groupStartLine;
                    prev.Name = DetectGroupName(currentLines, groupComments, groups.Count);
                    groups.Add(prev);
                    currentLines.Clear();
                    groupComments.Clear();
                    groupStartLine = i;
                }

                currentLines.Add(allLines[i]);
                if (nInit == 1 && currentLines.Count == 1)
                    groupStartLine = i;
            }

            // 마지막 그룹
            if (currentLines.Count > 0)
            {
                DhGroup last = new DhGroup();
                last.GroupIndex = groups.Count;
                last.DhText = string.Join("\r\n", currentLines.ToArray());
                last.StartTextLine = groupStartLine;
                last.Name = DetectGroupName(currentLines, groupComments, groups.Count);
                groups.Add(last);
            }

            return groups;
        }

