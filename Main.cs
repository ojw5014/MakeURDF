        /// <summary>
        /// strUrdfCommand 중간언어에서 mesh 명령의 파일명(STL) 목록 수집
        /// </summary>
        private static List<string> CollectMeshFilenames(string strUrdfCommand)
        {
            var result = new List<string>();
            foreach (string line in strUrdfCommand.Split('\n'))
            {
                string t = line.Trim();
                if (!t.StartsWith("mesh,")) continue;
                string[] parts = t.Split(',');
                if (parts.Length < 2) continue;
                string fname = parts[1].Trim();
                if (!string.IsNullOrEmpty(fname) && !result.Contains(fname))
                    result.Add(fname);
            }
            return result;
        }

        /// <summary>
        /// URDF/MJCF 파일 생성 및 저장 (브라우저 열기 없음)
        /// </summary>
        private bool ExportUrdfFiles()
        {
            try
            {
                string dhString = m_Builder.GenerateFullDh();
                if (string.IsNullOrWhiteSpace(dhString))
                {
                    Ojw.printf(txtLogHistory, "[Export] 먼저 로봇을 만들어주세요!\r\n");
                    return false;
                }

                // ── 폴더 결정 ──────────────────────────────────────
                string urdfDir  = GetUrdfOutputDir();
                string stlSub   = GetStlSubFolder();          // null이면 STL 서브폴더 없음
                string stlDir   = stlSub != null
                                  ? Path.Combine(urdfDir, stlSub)
                                  : urdfDir;
                string meshPrefix = stlSub;                   // URDF 내 경로 prefix (null이면 없음)

                Directory.CreateDirectory(urdfDir);
                Directory.CreateDirectory(stlDir);

                // ── URDF 중간언어 생성 ─────────────────────────────
                string strUrdfCommand = "";
                string strUrdfXml     = "";

                bool bShowSkeleton, bShowMesh;
                GetViewModeFlags(out bShowSkeleton, out bShowMesh);

                float fSkeletonSize = Ojw.CConvert.StrToFloat(txtSkeletonSize.Text);
                if (fSkeletonSize <= 0) fSkeletonSize = 10.0f;
                float fAxisSize = Ojw.CConvert.StrToFloat(txtAxisSize.Text);
                if (fAxisSize <= 0) fAxisSize = 20.0f;

                m_C3d.MakeDHSkeleton_Urdf(
                    false, true, bShowSkeleton, bShowMesh, fSkeletonSize, fAxisSize, Color.Violet,
                    dhString, 0, 0, 0, 0, 0, 0, 0,
                    ref txtMessage,
                    ref strUrdfCommand,
                    ref strUrdfXml);

                // ── STL 파일 복사 ──────────────────────────────────
                // STL 원본 위치: SetAseFile_Path("stl")로 설정된 경로 (예: Release\stl\)
                string stlSrcDir = Application.StartupPath.TrimEnd('\\')
                                   + (m_C3d != null ? m_C3d.GetAseFile_Path() : "\\stl\\");

                List<string> stlFiles = CollectMeshFilenames(strUrdfCommand);
                foreach (string fname in stlFiles)
                {
                    string justName = Path.GetFileName(fname);
                    // 후보 소스 경로: 1) SetAseFile_Path 폴더, 2) StartupPath 직접
                    string src = Path.Combine(stlSrcDir, justName);
                    if (!File.Exists(src))
                        src = Path.Combine(Application.StartupPath, justName);

                    string dst = Path.Combine(stlDir, justName);
                    if (File.Exists(src))
                    {
                        File.Copy(src, dst, true);
                        Ojw.printf(txtLogHistory, "[Export] STL 복사: {0}\r\n", justName);
                    }
                    else
                    {
                        Ojw.printf(txtLogHistory, "[Export] STL 없음(스킵): {0}\r\n", justName);
                    }
                }

                // ── URDF 재생성 (MeshFolder prefix 적용) ──────────
                var urdfBuilder = new Ojw.C3d.COjwUrdfBuilder_t();
                urdfBuilder.RobotName  = "ojw_robot";
                urdfBuilder.MeshFolder = meshPrefix;  // null이면 prefix 없음
                if (chkFixedBase.Checked)
                    urdfBuilder.SetWorldFixed();
                urdfBuilder.ParseCommands(strUrdfCommand);
                strUrdfXml = urdfBuilder.Build();

                // ── 파일 저장 (PyBullet/MuJoCo용 — mimic 보존) ────────
                string urdfPath = Path.Combine(urdfDir, "robot_stl.urdf");
                File.WriteAllText(urdfPath, strUrdfXml, Encoding.UTF8);
                Ojw.printf(txtLogHistory, "[Export] {0} 저장 완료\r\n", urdfPath);

                // ── Isaac Sim 전용 URDF 생성 (mimic 제거 등) ──────────
                List<string> isaacLog;
                string strIsaacXml = SanitizeUrdfForIsaacSim(strUrdfXml, stlDir, out isaacLog);
                string isaacPath = Path.Combine(urdfDir, "robot_stl_isaac.urdf");
                File.WriteAllText(isaacPath, strIsaacXml, Encoding.UTF8);
                Ojw.printf(txtLogHistory, "[Isaac] ── Isaac Sim 호환 후처리 ──────────────\r\n");
                Ojw.printf(txtLogHistory, "[Isaac] {0} 저장 완료\r\n", isaacPath);
                if (isaacLog.Count == 0)
                    Ojw.printf(txtLogHistory, "[Isaac] 변경 없음\r\n");
                else
                    foreach (string entry in isaacLog)
                        Ojw.printf(txtLogHistory, "{0}\r\n", entry);

                // 중간언어 저장
                File.WriteAllText(Path.Combine(urdfDir, "robot_commands.txt"),
                                  strUrdfCommand, Encoding.UTF8);

                // MJCF 생성 및 저장
                // MeshFolder가 설정된 경우 URDF filename에 이미 "stl/..." 경로가 포함되므로
                // meshdir에 중복 지정하지 않도록 "." 전달
                var mjcfBuilder = new Ojw.C3d.COjwUrdfBuilder_t();
                mjcfBuilder.RobotName  = "ojw_robot";
                mjcfBuilder.MeshFolder = meshPrefix;
                if (chkFixedBase.Checked)
                    mjcfBuilder.SetWorldFixed();
                mjcfBuilder.ParseCommands(strUrdfCommand);
                string strMjcfXml = mjcfBuilder.BuildMjcf("robot_stl.urdf", ".");

                string mjcfPath = Path.Combine(urdfDir, "robot_stl.xml");
                File.WriteAllText(mjcfPath, strMjcfXml, Encoding.UTF8);
                Ojw.printf(txtLogHistory, "[Export] {0} 저장 완료\r\n", mjcfPath);

                Ojw.printf(txtLogHistory, "[Export] 완료 → {0}\r\n", urdfDir);
                return true;
            }
            catch (Exception ex)
            {
                Ojw.printf(txtLogHistory, "[Export] 오류: {0}\r\n", ex.Message);
                return false;
            }
        }

        // ========================================
        // Isaac Sim 호환 URDF 후처리
        //   1) <mimic> 태그 제거 (Isaac Sim 4.5 미지원)
        //   2) STL 파일명 정규화: 대시(-) → 밑줄(_), 숫자 시작 → 'n_' 접두
        //      · URDF 내 filename 속성 수정
        //      · stlDir 내 실제 파일도 복사(새 이름)
        // ========================================
        private string SanitizeUrdfForIsaacSim(string urdf, string stlDir, out List<string> log)
        {
            log = new List<string>();

            // 1. <mimic> 태그 제거
            var mimicRx = new System.Text.RegularExpressions.Regex(
                @"[ \t]*<mimic[^/]*/>\r?\n?");
            System.Text.RegularExpressions.MatchCollection mimicMatches = mimicRx.Matches(urdf);
            if (mimicMatches.Count > 0)
            {
                urdf = mimicRx.Replace(urdf, "");
                log.Add(string.Format("[Isaac] <mimic> 태그 {0}개 제거 — Isaac Sim 4.5 미지원 (PyBullet은 원래 무시)", mimicMatches.Count));
            }

            // 2. STL 파일명 정규화
            // filename="stl/xl-430.stl" 형태에서 파일명 부분만 추출·변환
            var meshRx = new System.Text.RegularExpressions.Regex(
                @"filename=""((?:[^""/]*/)*)([^""/\s]+\.stl)""",
                System.Text.RegularExpressions.RegexOptions.IgnoreCase);

            var renamed = new System.Collections.Generic.Dictionary<string, string>(
                StringComparer.OrdinalIgnoreCase);

            urdf = meshRx.Replace(urdf, delegate(System.Text.RegularExpressions.Match m)
            {
                string dir   = m.Groups[1].Value;  // "stl/" 등 디렉토리 접두
                string fname = m.Groups[2].Value;  // "xl-430.stl"

                string safe = fname.Replace('-', '_');
                if (safe.Length > 0 && char.IsDigit(safe[0]))
                    safe = "n_" + safe;

                if (safe != fname && !renamed.ContainsKey(fname))
                {
                    renamed[fname] = safe;
                    Ojw.printf(string.Format("[Isaac] STL 파일명 변경: {0} → {1}\r\n", fname, safe));

                    // 실제 파일도 복사(새 이름)
                    string oldPath = Path.Combine(stlDir, fname);
                    string newPath = Path.Combine(stlDir, safe);
                    if (File.Exists(oldPath))
                        File.Copy(oldPath, newPath, true);
                    else
                        Ojw.printf(string.Format("[Isaac]   └ 경고: {0} 파일 없음 — URDF만 수정\r\n", fname));
                }

                return string.Format("filename=\"{0}{1}\"", dir, safe);
            });

            return urdf;
        }

